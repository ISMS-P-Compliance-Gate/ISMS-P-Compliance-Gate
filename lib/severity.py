"""
==================================================================
ISMS-P Compliance Gate — 심각도(Severity) 판정 공통 기준
==================================================================

[파일 역할]
이 프로젝트의 모든 점검 스크립트(scanners/ 아래 각 팀원 폴더의 check_*.py)는
발견한 문제마다 HIGH / MEDIUM / LOW / INFO 중 하나의 등급을 매겨야 한다.
이 파일은 "어떤 상황이 왜 HIGH인지 MEDIUM인지"를 판단하는 공통 기준과,
모든 항목에서 재사용 가능한 범용 판정 함수를 담고 있다.

[사용법]
이 파일은 '공통 severity.py'로, scanners 내부의 모든 파일들이 사용할 수 있는
로직만을 두고 있다. 아래 2가지 경우로 사용 가능하다.

항목별로 특수한 판정 로직이 필요한 경우) 'ex. SSH 포트가 열려 있으면 HIGH'처럼 항목별로 특수한 판정 로직이 필요한 팀원은 
scanners/{자기 폴더}/severity.py를 따로 두고, 거기서 이 파일의 공용 함수를 가져와 쓴다. 

항목별로 세부 로직이 필요 없는 경우)  이 파일을 바로 가져다 쓰면 된다.

==================================================================
심각도 판단 순서 (아래 번호 순서대로 확인, 먼저 해당하는 등급으로 확정)
==================================================================

① 법적 의무 위반인가?
   개인정보보호법 등 법령에 명시된 기준(예: 접속기록 보관기간 미달)을
   지키지 못한 경우.
   -> HIGH

② 추가 조건 없이 즉시 악용/침해가 가능한가?
   자격증명 유출, 인증 우회, 원격 코드 실행, 민감정보 직접 노출,
   또는 탐지·보안 시스템 자체가 꺼져 있어서 침해 여부조차 알 수 없는 경우.
   -> HIGH

③ 절차/프로세스가 미흡한가?
   설정값 자체엔 문제가 없지만, 그걸 다루는 규칙(승인 절차, 정책 문서 등)이
   없거나 안 지켜지는 경우. 예: 리뷰어 승인 없이 코드가 머지됨.
   -> MEDIUM

④ 기술적으로 위험은 있으나 추가 조건이 필요한가?
   예: 알려지지 않은 임의 포트가 외부에 열려있는 경우.
   (공격자가 "거기 뭐가 떠 있는지" 먼저 알아내야 하므로 ②보다 한 단계 낮음)
   -> MEDIUM

⑤ 문서화/기록이 부족한가?
   정기 점검 이력 미기록, 리소스 태그·네이밍 규칙 미준수 등.
   당장 침해로 이어지진 않지만 운영 관리가 허술한 경우.
   -> LOW

⑥ 위반은 아니지만, 확인한 내용을 증적으로 남기고 싶은가?
   예: "prod/staging Environment 분리 확인됨"처럼 PASS일 때 근거 기록용.
   -> INFO

(참고) 팀 내에서 합의된 컴플라이언스 관점 기준(①③⑤)과,
기술 스캔에서 흔히 쓰이는 공격 가능성 기준(②④)을 하나로 합친 것이다.
==================================================================
"""


def classify_from_external_tool(tool_severity: str) -> str:
    
    """
    Checkov, Gitleaks, CodeQL, Prowler 등 이미 검증된 외부 보안 도구가
    자체적으로 매긴 심각도 값을, 우리 프로젝트의 4단계
    (HIGH / MEDIUM / LOW / INFO)로 그대로 옮겨오는 함수.

    [Checkov란]
    Terraform, CloudFormation 같은 인프라 코드를 실제로 배포하기 전에,
    코드 안에 보안 설정 실수가 있는지 미리 검사해주는 오픈소스 정적 분석 도구.

    [왜 우리가 직접 판단하지 않고 그대로 옮기기만 하는가]
    2주짜리 짧은 프로젝트라, "탐지 로직을 새로 발명하지 않는다"는 원칙으로
    진행한다. Checkov 같은 도구는 이미 수백 개의 검증된 룰을 갖고 있고,
    그 도구가 CRITICAL/HIGH/MEDIUM/LOW로 판정해둔 걸 우리가 다시 판단하는
    건 원칙에 어긋난다. 이름만 우리 체계에 맞게 바꾸는 "번역" 역할만 한다.

    Args:
        tool_severity: 외부 도구가 반환한 문자열 (예: "CRITICAL", "HIGH")
    Returns:
        "HIGH" | "MEDIUM" | "LOW" | "INFO" 중 하나
    """
    
    mapping = {
        "CRITICAL": "HIGH",   # Fortis 체계에는 CRITICAL이 따로 없으므로 HIGH로 합침
        "HIGH": "HIGH",
        "MEDIUM": "MEDIUM",
        "LOW": "LOW",
        "INFO": "INFO",
    }
    
    # 외부 도구가 목록에 없는 낯선 값을 보내는 경우(예상 못 한 새 등급 추가 등),
    # 조용히 무시하거나 에러를 내는 대신 "일단 MEDIUM으로 간주"해서
    # 최소한 findings에서 놓치지 않도록 안전장치를 둔다.
    return mapping.get((tool_severity or "").upper(), "MEDIUM")
